# Maths in Python Part-2

import math

print(math.pi)
print(round(math.pi,2))

print(math.e)

#To find the sqrt
result=math.sqrt(25)
print(result)

#To find the ceiling value, Note: ceil() will always round a floating point number up
#If say x=9.4, then ceil(x)=10
print(math.ceil(9.4))

#floor() rounds the number down
print(math.floor(9.4))