# Maths in Python Part-1
x=3.145674
y=-5
z=5
result=round(x,2) #round() rounds the decimal places to the 2nd argument passed
print(result)

result1=abs(y) #abs() gives the distance away from 0 as a whole number
print(result1)

result3=pow(4,3) #This means: 4*4*4, pow(base, power)
print(result3)

result4=max(x,y,z) #max(arg1, arg2, arg3,...) gives max of all values passed
print(result4)

result4=min(x,y,z) #max(arg1, arg2, arg3,...) gives min of all values passed
print(result4)